import React, { useState, useEffect } from "react";
import { predictStudent } from "../services/api";
import { PredictionResult } from "./ResultCard";
import { 
  CheckCircle2, 
  AlertTriangle, 
  Lightbulb, 
  RefreshCw, 
  User, 
  Clock, 
  Award, 
  BookOpen, 
  Sparkles,
  Zap
} from "lucide-react";

export const Predictor: React.FC = () => {
  const [formData, setFormData] = useState({
    gender: "Male",
    age: 18,
    study_time: 12,
    attendance: 88,
    previous_score: 78,
    parent_education: "Bachelor",
    family_support: "Yes",
    internet_access: "Yes",
    extra_activities: "Yes",
    sleep_hours: 7.5
  });

  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState<{
    prediction: number;
    status: string;
    probability: number;
    estimated_grade: number;
    study_efficiency: number;
    recommendations: string[];
  } | null>(null);

  const handlePredict = async () => {
    setLoading(true);
    try {
      const response = await predictStudent(formData as Record<string, unknown>);
      if (response.success) {
        setResult(response as unknown as PredictionResult);
      }
    } catch (err) {
      console.error("Prediction error:", err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    handlePredict();
  }, [formData]);

  const loadPreset = (type: "high" | "at_risk" | "average") => {
    if (type === "high") {
      setFormData({
        gender: "Female",
        age: 18,
        study_time: 18,
        attendance: 96,
        previous_score: 88,
        parent_education: "Master",
        family_support: "Yes",
        internet_access: "Yes",
        extra_activities: "Yes",
        sleep_hours: 8
      });
    } else if (type === "at_risk") {
      setFormData({
        gender: "Male",
        age: 19,
        study_time: 4,
        attendance: 62,
        previous_score: 48,
        parent_education: "High School",
        family_support: "No",
        internet_access: "No",
        extra_activities: "No",
        sleep_hours: 5
      });
    } else {
      setFormData({
        gender: "Male",
        age: 18,
        study_time: 10,
        attendance: 80,
        previous_score: 68,
        parent_education: "Associate",
        family_support: "Yes",
        internet_access: "Yes",
        extra_activities: "No",
        sleep_hours: 7
      });
    }
  };

  return (
    <div className="space-y-8">
      {/* Banner */}
      <div className="bg-gradient-to-r from-slate-900 via-slate-800 to-emerald-950 p-6 rounded-2xl border border-slate-700/60 shadow-lg text-white">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
          <div>
            <div className="flex items-center gap-2 text-emerald-400 font-semibold text-xs tracking-wider uppercase mb-1">
              <Sparkles className="w-4 h-4" /> Live Machine Learning Inference Engine
            </div>
            <h2 className="text-2xl font-extrabold tracking-tight">Student Academic Performance Predictor</h2>
            <p className="text-slate-300 text-sm mt-1 max-w-2xl">
              Adjust demographic, academic, and behavioral parameters below to evaluate real-time performance predictions generated by the trained Random Forest Classifier model.
            </p>
          </div>
          <div className="flex flex-wrap gap-2">
            <button
              onClick={() => loadPreset("high")}
              className="px-3 py-1.5 bg-emerald-500/20 hover:bg-emerald-500/30 text-emerald-300 border border-emerald-500/40 rounded-lg text-xs font-semibold transition"
            >
              Preset: High Achiever
            </button>
            <button
              onClick={() => loadPreset("average")}
              className="px-3 py-1.5 bg-blue-500/20 hover:bg-blue-500/30 text-blue-300 border border-blue-500/40 rounded-lg text-xs font-semibold transition"
            >
              Preset: Average Student
            </button>
            <button
              onClick={() => loadPreset("at_risk")}
              className="px-3 py-1.5 bg-rose-500/20 hover:bg-rose-500/30 text-rose-300 border border-rose-500/40 rounded-lg text-xs font-semibold transition"
            >
              Preset: At-Risk Student
            </button>
          </div>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-8">
        {/* Input Parameters Form */}
        <div className="lg:col-span-7 bg-white p-6 rounded-2xl border border-slate-200 shadow-sm space-y-6">
          <div className="flex items-center justify-between border-b border-slate-100 pb-4">
            <h3 className="text-base font-bold text-slate-900 flex items-center gap-2">
              <User className="w-5 h-5 text-emerald-600" />
              Student Feature Parameters
            </h3>
            <span className="text-xs text-slate-500 bg-slate-100 px-2.5 py-1 rounded-full font-medium">
              10 Model Features
            </span>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-5">
            {/* Previous Exam Score */}
            <div className="space-y-1.5">
              <div className="flex justify-between items-center text-xs font-medium text-slate-700">
                <label className="flex items-center gap-1.5 font-semibold">
                  <Award className="w-3.5 h-3.5 text-indigo-500" /> Previous Score
                </label>
                <span className="text-indigo-600 font-bold text-sm">{formData.previous_score}%</span>
              </div>
              <input
                type="range"
                min="30"
                max="100"
                value={formData.previous_score}
                onChange={(e) => setFormData({ ...formData, previous_score: Number(e.target.value) })}
                className="w-full accent-indigo-600 h-2 bg-slate-100 rounded-lg cursor-pointer"
              />
              <p className="text-[11px] text-slate-400">Strongest feature weight (~32%)</p>
            </div>

            {/* Attendance Percentage */}
            <div className="space-y-1.5">
              <div className="flex justify-between items-center text-xs font-medium text-slate-700">
                <label className="flex items-center gap-1.5 font-semibold">
                  <CheckCircle2 className="w-3.5 h-3.5 text-emerald-500" /> Attendance Rate
                </label>
                <span className="text-emerald-600 font-bold text-sm">{formData.attendance}%</span>
              </div>
              <input
                type="range"
                min="40"
                max="100"
                value={formData.attendance}
                onChange={(e) => setFormData({ ...formData, attendance: Number(e.target.value) })}
                className="w-full accent-emerald-600 h-2 bg-slate-100 rounded-lg cursor-pointer"
              />
              <p className="text-[11px] text-slate-400">Key consistency indicator (~26%)</p>
            </div>

            {/* Weekly Study Hours */}
            <div className="space-y-1.5">
              <div className="flex justify-between items-center text-xs font-medium text-slate-700">
                <label className="flex items-center gap-1.5 font-semibold">
                  <Clock className="w-3.5 h-3.5 text-blue-500" /> Weekly Study Hours
                </label>
                <span className="text-blue-600 font-bold text-sm">{formData.study_time} hrs/wk</span>
              </div>
              <input
                type="range"
                min="1"
                max="30"
                step="0.5"
                value={formData.study_time}
                onChange={(e) => setFormData({ ...formData, study_time: Number(e.target.value) })}
                className="w-full accent-blue-600 h-2 bg-slate-100 rounded-lg cursor-pointer"
              />
              <p className="text-[11px] text-slate-400">Self-study effort (~18%)</p>
            </div>

            {/* Sleep Hours */}
            <div className="space-y-1.5">
              <div className="flex justify-between items-center text-xs font-medium text-slate-700">
                <label className="flex items-center gap-1.5 font-semibold">
                  <Zap className="w-3.5 h-3.5 text-amber-500" /> Sleep Hours
                </label>
                <span className="text-amber-600 font-bold text-sm">{formData.sleep_hours} hrs/night</span>
              </div>
              <input
                type="range"
                min="4"
                max="10"
                step="0.5"
                value={formData.sleep_hours}
                onChange={(e) => setFormData({ ...formData, sleep_hours: Number(e.target.value) })}
                className="w-full accent-amber-500 h-2 bg-slate-100 rounded-lg cursor-pointer"
              />
              <p className="text-[11px] text-slate-400">Cognitive rest factor</p>
            </div>

            {/* Parent Education */}
            <div className="space-y-1.5">
              <label className="block text-xs font-semibold text-slate-700">Parent Education Level</label>
              <select
                value={formData.parent_education}
                onChange={(e) => setFormData({ ...formData, parent_education: e.target.value })}
                className="w-full bg-slate-50 border border-slate-200 text-slate-800 rounded-lg p-2 text-xs focus:ring-2 focus:ring-emerald-500 focus:outline-none"
              >
                <option value="High School">High School</option>
                <option value="Associate">Associate Degree</option>
                <option value="Bachelor">Bachelor's Degree</option>
                <option value="Master">Master's Degree</option>
                <option value="Doctorate">Doctorate (PhD)</option>
              </select>
            </div>

            {/* Age & Gender */}
            <div className="grid grid-cols-2 gap-2">
              <div className="space-y-1.5">
                <label className="block text-xs font-semibold text-slate-700">Gender</label>
                <select
                  value={formData.gender}
                  onChange={(e) => setFormData({ ...formData, gender: e.target.value })}
                  className="w-full bg-slate-50 border border-slate-200 text-slate-800 rounded-lg p-2 text-xs focus:ring-2 focus:ring-emerald-500 focus:outline-none"
                >
                  <option value="Male">Male</option>
                  <option value="Female">Female</option>
                </select>
              </div>
              <div className="space-y-1.5">
                <label className="block text-xs font-semibold text-slate-700">Age</label>
                <input
                  type="number"
                  min="15"
                  max="25"
                  value={formData.age}
                  onChange={(e) => setFormData({ ...formData, age: Number(e.target.value) })}
                  className="w-full bg-slate-50 border border-slate-200 text-slate-800 rounded-lg p-2 text-xs focus:ring-2 focus:ring-emerald-500 focus:outline-none"
                />
              </div>
            </div>

            {/* Categorical Toggle Swtitches */}
            <div className="space-y-1.5 sm:col-span-2 grid grid-cols-3 gap-3 pt-2">
              <div className="bg-slate-50 p-2.5 rounded-lg border border-slate-200">
                <span className="block text-[11px] font-semibold text-slate-600 mb-1">Family Support</span>
                <button
                  onClick={() => setFormData({ ...formData, family_support: formData.family_support === "Yes" ? "No" : "Yes" })}
                  className={`w-full py-1 text-xs font-bold rounded-md transition ${
                    formData.family_support === "Yes" ? "bg-emerald-600 text-white" : "bg-slate-200 text-slate-600"
                  }`}
                >
                  {formData.family_support}
                </button>
              </div>

              <div className="bg-slate-50 p-2.5 rounded-lg border border-slate-200">
                <span className="block text-[11px] font-semibold text-slate-600 mb-1">Internet Access</span>
                <button
                  onClick={() => setFormData({ ...formData, internet_access: formData.internet_access === "Yes" ? "No" : "Yes" })}
                  className={`w-full py-1 text-xs font-bold rounded-md transition ${
                    formData.internet_access === "Yes" ? "bg-emerald-600 text-white" : "bg-slate-200 text-slate-600"
                  }`}
                >
                  {formData.internet_access}
                </button>
              </div>

              <div className="bg-slate-50 p-2.5 rounded-lg border border-slate-200">
                <span className="block text-[11px] font-semibold text-slate-600 mb-1">Extra Activities</span>
                <button
                  onClick={() => setFormData({ ...formData, extra_activities: formData.extra_activities === "Yes" ? "No" : "Yes" })}
                  className={`w-full py-1 text-xs font-bold rounded-md transition ${
                    formData.extra_activities === "Yes" ? "bg-emerald-600 text-white" : "bg-slate-200 text-slate-600"
                  }`}
                >
                  {formData.extra_activities}
                </button>
              </div>
            </div>
          </div>
        </div>

        {/* Prediction Results Panel */}
        <div className="lg:col-span-5 space-y-6">
          {result && (
            <div className={`p-6 rounded-2xl border shadow-sm transition-all ${
              result.prediction === 1
                ? "bg-emerald-50/70 border-emerald-200 text-emerald-950"
                : "bg-rose-50/70 border-rose-200 text-rose-950"
            }`}>
              <div className="flex items-center justify-between border-b pb-4 border-slate-200/60">
                <div>
                  <span className="text-xs font-semibold text-slate-500 uppercase tracking-wider">Model Prediction Outcome</span>
                  <h3 className="text-xl font-extrabold flex items-center gap-2 mt-0.5">
                    {result.prediction === 1 ? (
                      <>
                        <CheckCircle2 className="w-6 h-6 text-emerald-600" />
                        High Performance (Pass)
                      </>
                    ) : (
                      <>
                        <AlertTriangle className="w-6 h-6 text-rose-600" />
                        Low Performance (At-Risk)
                      </>
                    )}
                  </h3>
                </div>
                <div className={`text-right px-3 py-1.5 rounded-xl border font-black text-sm ${
                  result.prediction === 1 ? "bg-emerald-100 border-emerald-300 text-emerald-800" : "bg-rose-100 border-rose-300 text-rose-800"
                }`}>
                  Score ~{result.estimated_grade}%
                </div>
              </div>

              {/* Probability Meter Gauge */}
              <div className="mt-5 space-y-2">
                <div className="flex justify-between items-center text-xs font-bold">
                  <span className="text-slate-600">Pass Probability Confidence</span>
                  <span className={result.prediction === 1 ? "text-emerald-700" : "text-rose-700"}>
                    {result.probability}%
                  </span>
                </div>
                <div className="w-full h-3 bg-slate-200/80 rounded-full overflow-hidden p-0.5">
                  <div
                    className={`h-full rounded-full transition-all duration-500 ${
                      result.prediction === 1
                        ? "bg-gradient-to-r from-emerald-500 to-teal-400"
                        : "bg-gradient-to-r from-rose-500 to-amber-500"
                    }`}
                    style={{ width: `${Math.max(result.probability, 5)}%` }}
                  />
                </div>
                <div className="flex justify-between text-[10px] text-slate-400 font-medium">
                  <span>0% (Fail)</span>
                  <span>60% (Pass Cutoff)</span>
                  <span>100% (High Pass)</span>
                </div>
              </div>

              {/* Metrics Grid */}
              <div className="grid grid-cols-2 gap-3 mt-5">
                <div className="bg-white/80 p-3 rounded-xl border border-slate-200/80 shadow-2xs">
                  <span className="text-[11px] font-medium text-slate-500 block">Study Efficiency Index</span>
                  <span className="text-base font-bold text-slate-900">{result.study_efficiency}</span>
                  <span className="text-[10px] text-slate-400 block">Previous Score / Study Hour</span>
                </div>
                <div className="bg-white/80 p-3 rounded-xl border border-slate-200/80 shadow-2xs">
                  <span className="text-[11px] font-medium text-slate-500 block">Assessed Risk Tier</span>
                  <span className={`text-base font-bold ${
                    result.probability >= 80 ? "text-emerald-600" : result.probability >= 60 ? "text-amber-600" : "text-rose-600"
                  }`}>
                    {result.probability >= 80 ? "Low Risk" : result.probability >= 60 ? "Moderate" : "High Risk"}
                  </span>
                  <span className="text-[10px] text-slate-400 block">Academic Intervention Level</span>
                </div>
              </div>

              {/* Actionable Recommendations */}
              <div className="mt-5 pt-4 border-t border-slate-200/60 space-y-2">
                <h4 className="text-xs font-bold text-slate-800 flex items-center gap-1.5">
                  <Lightbulb className="w-4 h-4 text-amber-500" /> Actionable Academic Recommendations
                </h4>
                <ul className="space-y-1.5 text-xs text-slate-700">
                  {result.recommendations.map((rec, i) => (
                    <li key={i} className="flex items-start gap-2 bg-white/60 p-2 rounded-lg border border-slate-200/50">
                      <span className="text-emerald-600 font-bold">•</span>
                      <span>{rec}</span>
                    </li>
                  ))}
                </ul>
              </div>
            </div>
          )}

          {/* Model Specification Box */}
          <div className="bg-white p-5 rounded-2xl border border-slate-200 text-xs text-slate-600 space-y-2 shadow-2xs">
            <h4 className="font-bold text-slate-900 flex items-center gap-2">
              <BookOpen className="w-4 h-4 text-emerald-600" /> Pipeline Technical Specification
            </h4>
            <p>
              This live prediction is driven by an ensemble <strong>Random Forest Classifier</strong> trained on 800 student records with 5-fold cross-validation.
            </p>
            <div className="grid grid-cols-2 gap-2 pt-2 text-[11px] text-slate-500 border-t border-slate-100">
              <div>• Algorithm: Random Forest (n_estimators=100)</div>
              <div>• Feature Scaling: StandardScaler</div>
              <div>• Encoding: Label Encoding</div>
              <div>• Decision Boundary: 60% Final Grade</div>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
